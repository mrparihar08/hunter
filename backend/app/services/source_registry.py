def get_registered_sources(category: Optional[str] = None) -> List[SourceRegistryItem]:
    """Returns a list of all registered discovery sources, optionally filtered by category."""
    items = []
    for s_id, s_data in SOURCE_REGISTRY.items():
        if category and category.lower() != "all" and s_data["category"] != category.lower():
            continue
        items.append(
            SourceRegistryItem(
                source_id=s_data["source_id"],
                name=s_data["name"],
                category=s_data["category"],
                source_mode=s_data["source_mode"],
                description=s_data["description"],
                is_automated=s_data["is_automated"],
                auth_status=s_data["auth_status"],
                supported_filters=s_data.get("supported_filters", []),
                is_indirect=s_data.get("is_indirect", False),
                compliance_notes=s_data.get("compliance_notes"),
                example_url=s_data.get("example_url"),
            )
        )
    return items


def get_source_definition(source_id: str) -> Optional[Dict[str, Any]]:
    """Retrieves metadata definition for a specific source ID."""
    return SOURCE_REGISTRY.get(source_id.lower().strip())
